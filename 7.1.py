print("система рейтинга продуктов")
score = int(input("Введите рейтинг(1-10): "))

match score:
    case 1 | 2 | 3:
        print(f"Рейтинг {score}; Плохой продукт ❌ Не рекомендую")
    case  4 | 5 | 6:
        print(f"Рейтинг {score}; Средний продукт 🥱 Под пиво пойдет")
    case  7 | 8:
        print(f"Рейтинг {score}; Хороший продукт 👌 Рекомендую")
    case 9 | 10:
        print(f"Рейтинг {score}; Отличный продукт 😍 Маст-хев")
    case _:
        print("ты ваще дурной?⁉️⁉️")